package io.quarkiverse.langchain4j.agentic.viewer.it;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;
import java.util.zip.ZipFile;

import org.junit.jupiter.api.Test;

/**
 * The production build of the sample app (target/quarkus-app, built before the failsafe tests) carries nothing of the
 * Dev UI (F6.4): no runtime-dev or deployment artifact, class or Dev UI resource; only the runtime artifact's inert
 * topology records, SPI and config.
 */
class ProdArtifactIT {

    private static final Path APP = Path.of("target", "quarkus-app");
    private static final List<String> FORBIDDEN_ENTRIES = List.of(
            "io/quarkiverse/langchain4j/agentic/viewer/runtime/dev/",
            "io/quarkiverse/langchain4j/agentic/viewer/deployment/",
            "dev-ui/qwc-agentic");

    private static List<Path> jars() throws IOException {
        try (Stream<Path> files = Files.walk(APP)) {
            return files.filter(file -> file.toString().endsWith(".jar")).toList();
        }
    }

    @Test
    void noDevUiArtifact() throws IOException {
        // a native-only package (quarkus.package.jar.enabled=false) has no quarkus-app: NativeArtifactIT checks it
        assumeTrue(Files.isDirectory(APP), "no JVM package in " + APP.toAbsolutePath());
        List<String> names = jars().stream().map(jar -> jar.getFileName().toString()).toList();
        assertTrue(names.stream().anyMatch(name -> name.startsWith("io.quarkiverse.langchain4j.quarkus-langchain4j-agentic-viewer-")),
                "the runtime artifact is there: " + names);
        assertTrue(names.stream().noneMatch(name -> name.contains("agentic-viewer-dev") || name.contains("agentic-viewer-deployment")),
                names::toString);
        String dependencies = Files.readString(APP.resolve("quarkus-app-dependencies.txt"));
        assertTrue(!dependencies.contains("agentic-viewer-dev") && !dependencies.contains("agentic-viewer-deployment"),
                dependencies);
    }

    @Test
    void noDevUiClassOrResource() throws IOException {
        assumeTrue(Files.isDirectory(APP), "no JVM package in " + APP.toAbsolutePath());
        List<String> found = new ArrayList<>();
        for (Path jar : jars()) {
            try (ZipFile zip = new ZipFile(jar.toFile())) {
                zip.stream().map(entry -> entry.getName())
                        .filter(name -> FORBIDDEN_ENTRIES.stream().anyMatch(name::startsWith)
                                // generated by a viewer build step (Dev UI recorder, JSON-RPC, beans)
                                || name.contains("AgenticViewerProcessor") || name.contains("AgenticViewerRecorder"))
                        .forEach(name -> found.add(jar.getFileName() + "!" + name));
            }
        }
        assertEquals(List.of(), found);
    }
}
